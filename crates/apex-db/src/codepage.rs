//! 8-bit text in a Windows or DOS code page: Jet 3 databases store text in
//! the database's code page, dBase files in the one their language driver
//! (or a `.cpg` file next to them) names.

/// Text in code page `cp` (Windows numbers: 1252, 850, 65001...).
pub fn decode(data: &[u8], cp: u16) -> String {
    match cp {
        437 => dos(data, &CP437_80),
        850 => dos(data, &CP850_80),
        65001 => String::from_utf8_lossy(data).into_owned(),
        _ => {
            let enc = encoding(cp).unwrap_or(encoding_rs::WINDOWS_1252);
            enc.decode_without_bom_handling(data).0.into_owned()
        }
    }
}

/// The encoding_rs encoding of a Windows code page.
fn encoding(cp: u16) -> Option<&'static encoding_rs::Encoding> {
    use encoding_rs::*;
    Some(match cp {
        866 => IBM866,
        874 => WINDOWS_874,
        932 => SHIFT_JIS,
        936 => GBK,
        949 => EUC_KR,
        950 => BIG5,
        1250 => WINDOWS_1250,
        1251 => WINDOWS_1251,
        1252 => WINDOWS_1252,
        1253 => WINDOWS_1253,
        1254 => WINDOWS_1254,
        1255 => WINDOWS_1255,
        1256 => WINDOWS_1256,
        1257 => WINDOWS_1257,
        1258 => WINDOWS_1258,
        10000 => MACINTOSH,
        10007 => X_MAC_CYRILLIC,
        20866 => KOI8_R,
        21866 => KOI8_U,
        28591 => WINDOWS_1252,
        28592 => ISO_8859_2,
        28595 => ISO_8859_5,
        28597 => ISO_8859_7,
        28605 => ISO_8859_15,
        _ => return None,
    })
}

/// The code page a name means ("UTF-8", "1252", "CP1251", "ISO-8859-1"),
/// as `.cpg` files next to shapefiles say.
pub fn from_name(name: &str) -> Option<u16> {
    let n = name.trim().to_ascii_uppercase().replace(['_', ' '], "-");
    let n = n.trim_start_matches("CP").trim_start_matches("WINDOWS-").trim_start_matches("ANSI-").trim_start_matches("IBM");
    if let Ok(v) = n.parse::<u16>() {
        return Some(v);
    }
    Some(match n {
        "UTF-8" | "UTF8" => 65001,
        "ISO-8859-1" | "LATIN1" | "LATIN-1" => 28591,
        "ISO-8859-2" => 28592,
        "ISO-8859-5" => 28595,
        "ISO-8859-7" => 28597,
        "ISO-8859-15" => 28605,
        "KOI8-R" => 20866,
        "KOI8-U" => 21866,
        "BIG5" => 950,
        "GBK" | "GB2312" => 936,
        "SHIFT-JIS" | "SJIS" => 932,
        "EUC-KR" => 949,
        _ => return None,
    })
}

fn dos(data: &[u8], high: &[u16; 128]) -> String {
    data.iter().map(|&b| if b < 0x80 { b as char } else { char::from_u32(high[(b - 0x80) as usize] as u32).unwrap_or('\u{FFFD}') }).collect()
}

