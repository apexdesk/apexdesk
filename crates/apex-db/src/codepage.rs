#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pages() {
        assert_eq!(decode(b"caf\x82", 437), "café");
        assert_eq!(decode(b"\xa4", 850), "ñ");
        assert_eq!(decode(b"\xef\xf0", 1251), "пр");
        assert_eq!(decode("ñ".as_bytes(), 65001), "ñ");
        assert_eq!(from_name("UTF-8"), Some(65001));
        assert_eq!(from_name("1251"), Some(1251));
        assert_eq!(from_name("ANSI 1252"), Some(1252));
    }
}
